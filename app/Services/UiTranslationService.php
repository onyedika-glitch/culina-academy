    public static function translate(string $string, ?string $lang = null): string
    {
        $lang = PolylangService::normalizeCode($lang ?? PolylangService::currentLanguage());
        $string = trim($string);

        if ($string === '') {
            return $string;
        }

        // Exact match for this language only.
        if (isset(static::$menuTranslations[$lang][$string])) {
            return static::$menuTranslations[$lang][$string];
        }

        // Map known foreign chrome labels to the English key, then translate into $lang.
        $canonicalKey = static::$aliasMap[$string] ?? $string;

        if (isset(static::$menuTranslations[$lang][$canonicalKey])) {
            return static::$menuTranslations[$lang][$canonicalKey];
        }

        // English: prefer the canonical English key when we recognised an alias.
        // Other languages: keep the stored string — never substitute English/Italian copy.
        if ($lang === 'en' && $canonicalKey !== $string) {
            return $canonicalKey;
        }

        return $string;
    }

    public static function translateMenuTitle(string $title, ?string $lang = null): string
    {
        return static::translate($title, $lang);
    }
